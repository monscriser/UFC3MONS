#pragma once
#include "ufc_library.h"
#include <rex/cvar.h>
#include <rex/logging.h>
REXCVAR_DEFINE_STRING(ufc_session_id,"","Log","Opaque session identity generated by the launcher");
REXCVAR_DEFINE_STRING(ufc_session_edition,"","Log","Edition selected by the launcher, verified against the running app");
namespace ufc {
inline fs::path ConfiguratorLogPath(){
 Settings settings;settings.Load({});
 if(!settings.write_logs){rex::cvar::SetFlagByName("log_level","off");
#ifdef _WIN32
  return fs::path(L"NUL");
#else
  return fs::path("/dev/null");
#endif
 }
 auto session=rex::cvar::GetFlagByName("ufc_session_id");if(session.empty()){session=NewLogSessionId();rex::cvar::SetFlagByName("ufc_session_id",session);}
 // Use a generated directory name, never an arbitrary command-line identity as a path.
 static const auto directory=RegistryDirectory()/"logs"/("configurator-"+NewLogSessionId());
 AtomicText(directory/"launch.txt",std::string("manifest_format=2\nbuild_id=")+BuildId+"\nsession_id="+session+"\nlaunch_mode=configurator\nedition=launcher\nin_game_mode=not_applicable\nlogs_enabled=1\n");
 return directory/"ufc3.log";
}
inline void LogSessionIdentity(const char* edition,bool configurator){
 auto session=rex::cvar::GetFlagByName("ufc_session_id");if(session.empty()){session=NewLogSessionId();rex::cvar::SetFlagByName("ufc_session_id",session);}
 const auto selected=rex::cvar::GetFlagByName("ufc_session_edition");
 REXLOG_INFO("[ufc-session] manifest_format=2 build_id={} session_id={} edition={} launcher_edition={} launch_mode={} in_game_mode={}",BuildId,session,edition,selected.empty()?"direct":selected,configurator?"configurator":"gameplay",configurator?"not_applicable":"not_observed_by_launcher");
}
}
