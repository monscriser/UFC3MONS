"""Gera o patch de acentos das fontes do Reborn (IndustryMenu.xpr e BroadcastDIN.xpr compartilham a textura).
Uso: gerar_patch.py <IndustryMenu.xpr> <BroadcastDIN.xpr> <saida.h>. Roda acentos_fonte.py na IndustryMenu, compara a
textura e grava trechos (offset, bytes) aplicáveis aos dois arquivos, com os hashes de origem e de resultado."""
import hashlib, subprocess, sys, os, tempfile
here = os.path.dirname(os.path.abspath(__file__))
ind, bro, out = sys.argv[1:4]
tmp = os.path.join(tempfile.gettempdir(), "ufc-industry-acentos.xpr")
subprocess.run([sys.executable, os.path.join(here, "acentos_fonte.py"), ind, tmp], check=True, cwd=tempfile.gettempdir())
a = open(ind, "rb").read(); p = open(tmp, "rb").read(); b = open(bro, "rb").read()
assert len(a) == len(p) == len(b)
assert a[0x2000:] == b[0x2000:], "texturas diferentes"
runs = []; i = 0x2000
while i < len(a):
    if a[i] != p[i]:
        j = i
        while j < len(a) and (a[j] != p[j] or (j + 8 < len(a) and a[j:j+8] != p[j:j+8])): j += 1
        runs.append((i, p[i:j])); i = j
    else: i += 1
def patched(src):
    s = bytearray(src)
    for off, data in runs: s[off:off + len(data)] = data
    return bytes(s)
h = lambda x: hashlib.sha256(x).hexdigest()
L = ["#pragma once", "// Generated by bancada/fonte-acentos/gerar_patch.py (do not edit). Accents drawn on the Reborn font's",
     "// uppercase accented glyphs (IndustryMenu.xpr and BroadcastDIN.xpr share the texture).",
     "#include <cstddef>", "#include <cstdint>", "namespace ufc_font_accents {",
     "struct Run{size_t offset;size_t size;const unsigned char* data;};"]
for k, (off, data) in enumerate(runs):
    L.append(f"inline constexpr unsigned char R{k}[]={{" + ",".join(str(x) for x in data) + "};")
L.append("inline constexpr Run Runs[]={" + ",".join(f"{{{off},{len(data)},R{k}}}" for k, (off, data) in enumerate(runs)) + "};")
L.append(f'inline constexpr const char* IndustrySource="{h(a)}"; inline constexpr const char* IndustryTarget="{h(patched(a))}";')
L.append(f'inline constexpr const char* BroadcastSource="{h(b)}"; inline constexpr const char* BroadcastTarget="{h(patched(b))}";')
L.append(f"inline constexpr size_t FileSize={len(a)};")
L.append("}  // namespace ufc_font_accents")
open(out, "w", newline="").write(chr(10).join(L) + chr(10))
print("runs", len(runs), "bytes", sum(len(d) for _, d in runs), h(patched(a))[:12], h(patched(b))[:12])
